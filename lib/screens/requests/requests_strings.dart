String langCode(BuildContext context) => context.watch<LanguageProvider>().locale.languageCode;

/// tr(context, 'key') — watches the language, so text updates when it changes.
String tr(BuildContext context, String key) {
  final l = langCode(context);
  return _s[l]?[key] ?? _s['en']![key] ?? key;
}

/// Same as tr() but safe to call outside build (does not subscribe).
String trRead(BuildContext context, String key) {
  final l = context.read<LanguageProvider>().locale.languageCode;
  return _s[l]?[key] ?? _s['en']![key] ?? key;
}